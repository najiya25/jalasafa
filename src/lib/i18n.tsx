const DICT: Record<Lang, Record<TKey, string>> = { en, ml, hi, ta };

// ── current language (module-level so labels.ts can read it outside React) ─

const LANG_KEY = 'jalsafa.lang';

function readStoredLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_KEY);
    return v === 'ml' || v === 'hi' || v === 'ta' ? v : 'en';
  } catch {
    return 'en';
  }
}

let currentLang: Lang = typeof localStorage === 'undefined' ? 'en' : readStoredLang();

/** Language currently in effect — usable from plain modules (labels.ts). */
export function getLang(): Lang {
  return currentLang;
}

type Vars = Record<string, string | number>;

function translate(lang: Lang, key: TKey, vars?: Vars): string {
  const table = DICT[lang] ?? DICT.en;
  let out = table[key] ?? DICT.en[key] ?? String(key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  }
  return out;
}

/** Translate outside React (module-level helpers such as labels.ts). */
export function tx(key: TKey, vars?: Vars): string {
  return translate(currentLang, key, vars);
}

// ── React context ──────────────────────────────────────────────────────────

interface I18nValue {
  lang: Lang;
  setLang: (next: Lang) => void;
  t: (key: TKey, vars?: Vars) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(currentLang);

  const setLang = (next: Lang): void => {
    currentLang = next;
    setLangState(next);
    try {
      localStorage.setItem(LANG_KEY, next); // survives reload, no data reset
    } catch {
      /* storage blocked — language still applies for this session */
    }
  };

  useEffect(() => {
    currentLang = lang;
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo<I18nValue>(
    () => ({ lang, setLang, t: (key, vars) => translate(lang, key, vars) }),
    [lang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

/** Every component that renders label text consumes this so it re-renders on change. */
export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (ctx) return ctx;
  // Fallback (should not happen — providers wrap App in main.tsx).
  return { lang: 'en', setLang: () => undefined, t: (key, vars) => translate('en', key, vars) };
}
