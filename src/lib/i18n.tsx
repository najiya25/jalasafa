/**
 * Central translation system (language switcher feature).
 *
 * • One dictionary per language. `en` is the source of truth: its values are
 *   the app's original English strings, byte-for-byte, so existing behaviour
 *   (and the automated QA suite) is untouched when the default language is on.
 * • `ml` / `hi` / `ta` are typed as Record<TKey, string> — TypeScript forces
 *   FULL coverage; a missing key is a compile error, not a silent English leak.
 * • `t(key, vars)` renders with {placeholder} substitution.
 * • The choice persists in localStorage (`jalsafa.lang`) — no reload, no data
 *   reset. `labels.ts` reads the same dictionary via `tx()` so status/condition
 *   labels translate too, even where rendered outside a t() call.
 *
 * Long-form prose that is NOT part of the required UI-label set (the footer,
 * server-sent workflow strings, Leaflet popups) stays English — noted as a
 * prototype limitation in the README.
 */
